import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { describe, test } from 'node:test';
import { fileURLToPath } from 'node:url';
import { resolveBash } from './lib/bash.ts';

const script = path.join(path.dirname(fileURLToPath(import.meta.url)), 'check-commit-msg.sh');
const bash = resolveBash() as string; // null only without a usable bash, and then every suite is skipped
const dir = mkdtempSync(path.join(os.tmpdir(), 'commit-msg-'));
process.on('exit', () => rmSync(dir, { recursive: true, force: true }));

const viaFile = (msg: string, ...flags: string[]) => {
  const file = path.join(dir, 'MSG');
  writeFileSync(file, msg);
  return spawnSync(bash, [script, ...flags, file], { encoding: 'utf8' });
};
const viaStdin = (msg: string, ...flags: string[]) =>
  spawnSync(bash, [script, ...flags, '-'], { input: msg, encoding: 'utf8' });

const coAuthor = ['Co-Authored', 'By: A <a@example.com>'].join('-');
const good = 'feat(cart): add quantity stepper\n\nThe cart now has a stepper.\n';

describe('check-commit-msg.sh', { skip: bash ? false : 'bash not found' }, () => {
  test('accepts a full message from a file and from stdin', () => {
    assert.equal(viaFile(good).status, 0);
    assert.equal(viaStdin(good).status, 0);
  });
  test('accepts all header shapes', () => {
    for (const h of ['fix: handle empty cart', 'feat!: drop old api', 'ci(hooks)!: tighten checks']) {
      assert.equal(viaFile(`${h}\n\nbody\n`).status, 0, h);
    }
  });
  test('ignores git comment lines', () => {
    assert.equal(viaFile(`${good}# Please enter the commit message\n# more\n`).status, 0);
    assert.equal(viaFile(`# comment first\n${good}`).status, 0);
  });
  test('rejects a message without a body', () => {
    for (const m of ['feat: add thing\n', 'feat: add thing\n\n', 'feat: add thing\n\n  \n# only comments\n']) {
      const r = viaFile(m);
      assert.equal(r.status, 1, JSON.stringify(m));
      assert.match(r.stderr, /body/);
    }
  });
  test('rejects a body that follows the header without a blank line', () => {
    const r = viaFile('feat: add thing\nbody directly\n');
    assert.equal(r.status, 1);
    assert.match(r.stderr, /line 2 must be blank/);
  });
  test('rejects bad headers', () => {
    for (const h of [
      'add thing',
      'feature: add thing',
      'feat: Add thing',
      'feat(Cart): add thing',
      'feat:add thing',
      'feat: add thing.',
      `feat: ${'a'.repeat(70)}`,
    ]) {
      assert.equal(viaFile(`${h}\n\nbody\n`).status, 1, h);
    }
  });
  test('rejects non-ASCII anywhere', () => {
    const r = viaFile('feat: add thing\n\nSepete ürün ekledim\n');
    assert.equal(r.status, 1);
    assert.match(r.stderr, /non-ASCII/);
    assert.equal(viaFile('feat: add café\n\nbody\n').status, 1);
  });
  test('rejects co-author, generated-by and sign-off lines', () => {
    for (const line of [coAuthor, 'Generated with a tool', 'generated by a tool', 'Signed-off-by: A <a@example.com>']) {
      assert.equal(viaFile(`feat: add thing\n\nbody\n\n${line}\n`).status, 1, line);
    }
  });
  test('merge and revert headers are exempt from every check', () => {
    assert.equal(viaFile("Merge branch 'x' into main\n").status, 0);
    assert.equal(viaFile('Revert "feat: add thing"\n\nThis reverts commit abc.\n').status, 0);
    assert.equal(viaFile('Revert "feat: add thing"\n').status, 0);
  });
});

describe('check-commit-msg.sh --header-only', { skip: bash ? false : 'bash not found' }, () => {
  test('accepts a valid title without a body', () => {
    assert.equal(viaStdin('feat(cart): add quantity stepper\n', '--header-only').status, 0);
    assert.equal(viaStdin('feat(cart): add quantity stepper', '--header-only').status, 0);
  });
  test('only looks at the first line', () => {
    assert.equal(viaFile('feat: add thing\nno blank line\n', '--header-only').status, 0);
  });
  test('still validates the header and ASCII', () => {
    assert.equal(viaStdin('Add thing\n', '--header-only').status, 1);
    assert.equal(viaStdin('feat: add thing.\n', '--header-only').status, 1);
    assert.equal(viaStdin('feat: add café\n', '--header-only').status, 1);
  });
});
